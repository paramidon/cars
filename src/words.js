const last = {};

export function phrase(kind) {
  const list = WORDS[kind];
  if (!list || list.length === 0) return '';
  let w = list[Math.floor(Math.random() * list.length)];
  if (list.length > 1) while (w === last[kind]) w = list[Math.floor(Math.random() * list.length)];
  last[kind] = w;
  return w;
}

