/** Надпись серии из n убийств ('' — ещё не серия). */
export function seriesPhrase(n) {
  if (n < 2) return '';
  const top = SERIES.length - 1;
  const list = SERIES[Math.min(n, top)];
  let w = list[Math.floor(Math.random() * list.length)];
  if (list.length > 1) while (w === last.series) w = list[Math.floor(Math.random() * list.length)];
  last.series = w;
  return n > top ? `${w} ×${n}` : w;
}
